package lk.jiat.flexzone.dto;

public class ProvinceDTO {
    private int pid;
    private String provinces;

    public ProvinceDTO() {

    }

    public int getPid() {
        return pid;
    }

    public void setPid(int pid) {
        this.pid = pid;
    }

    public String getProvinces() {
        return provinces;
    }

    public void setProvinces(String provinces) {
        this.provinces = provinces;
    }
}
